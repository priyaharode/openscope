import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';
import { ResearchSource, Investigation } from '../types';

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

export function formatDate(dateString?: string): string {
  if (!dateString) return 'Undated';
  try {
    const d = new Date(dateString);
    if (isNaN(d.getTime())) return dateString;
    return d.toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric'
    });
  } catch {
    return dateString;
  }
}

export function generateBibTeX(source: ResearchSource): string {
  const authorStr = source.authors.join(' and ');
  const cleanId = source.id.replace(/[^a-zA-Z0-9]/g, '_');
  const type = source.type === 'journal' ? 'article' : source.type === 'conference' ? 'inproceedings' : 'misc';

  return `@${type}{${cleanId},
  title = {${source.title}},
  author = {${authorStr}},
  year = {${source.year}},
  journal = {${source.venue || source.source}},
  url = {${source.url}}${source.doi ? `,\n  doi = {${source.doi}}` : ''}
}`;
}

export function exportInvestigationToMarkdown(inv: Investigation): string {
  let md = `# Research Investigation: ${inv.title}\n\n`;
  md += `**Topic:** ${inv.topic}  \n`;
  md += `**Status:** ${inv.status.toUpperCase()}  \n`;
  md += `**Created:** ${formatDate(inv.createdAt)} | **Updated:** ${formatDate(inv.updatedAt)}  \n`;
  md += `**Tags:** ${inv.tags.join(', ')}\n\n`;

  if (inv.description) {
    md += `## Abstract / Scope\n${inv.description}\n\n`;
  }

  md += `## Research Notes\n${inv.notes}\n\n`;

  md += `## Key Findings (${inv.savedFindings.length})\n\n`;
  inv.savedFindings.forEach((f, i) => {
    md += `### ${i + 1}. [${f.type.toUpperCase()}] ${f.title}\n`;
    md += `${f.content}\n`;
    if (f.sourceTitle) {
      md += `*Source:* ${f.sourceTitle}\n`;
    }
    md += `*Logged on:* ${formatDate(f.createdAt)}\n\n`;
  });

  md += `## Pinned Sources & Literature (${inv.savedSources.length})\n\n`;
  inv.savedSources.forEach((s, i) => {
    md += `### ${i + 1}. ${s.title} (${s.year})\n`;
    md += `- **Authors:** ${s.authors.join(', ')}\n`;
    md += `- **Venue:** ${s.venue || s.source}\n`;
    md += `- **Citations:** ${s.citations}\n`;
    md += `- **URL:** [Link](${s.url})\n`;
    md += `- **Abstract:** ${s.abstract}\n\n`;
  });

  if (inv.timelineItems.length > 0) {
    md += `## Discovered Timeline\n\n`;
    inv.timelineItems.forEach(t => {
      md += `- **${t.year}** [${t.category}]: **${t.title}** — ${t.description}\n`;
    });
    md += `\n`;
  }

  md += `---\n*Generated by OpenScope — Open-Source Research Intelligence Dashboard*\n`;
  return md;
}

export function downloadFile(content: string, filename: string, type = 'text/plain') {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
